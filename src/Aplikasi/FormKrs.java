    private void btnTambahActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnTambahActionPerformed
        try {

            Connection conn = Koneksi.getKoneksi();

            // Ambil NIM
            String mahasiswa
                    = cbMahasiswa.getSelectedItem().toString();

            String nim
                    = mahasiswa.split(" - ")[0];

            // Ambil Kode Matkul
            String matkul
                    = cbMatkul.getSelectedItem().toString();

            String kodeMatkul
                    = matkul.split(" - ")[0];

            String sql
                    = "INSERT INTO krs(nim,kode_matkul,semester,tahun_ajaran) "
                    + "VALUES(?,?,?,?)";

            PreparedStatement pst
                    = conn.prepareStatement(sql);

            pst.setString(1, nim);

            pst.setString(2, kodeMatkul);

            pst.setString(3,
                    cbSemester.getSelectedItem().toString());

            pst.setString(4,
                    txtTahun.getText());

            pst.executeUpdate();

            JOptionPane.showMessageDialog(this,
                    "KRS berhasil disimpan");

            tampilData();

            resetForm();

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());
        }
    }//GEN-LAST:event_btnTambahActionPerformed

