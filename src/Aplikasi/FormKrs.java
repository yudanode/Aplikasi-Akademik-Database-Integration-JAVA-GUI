    private void tampilData() {

        try {
            DefaultTableModel model
                    = new DefaultTableModel();
            model.addColumn("ID");
            model.addColumn("NIM");
            model.addColumn("Kode Mata Kuliah");
            model.addColumn("Semester");
            model.addColumn("Tahun Ajaran");

            model.setRowCount(0);

            Connection conn = Koneksi.getKoneksi();

            String sql
                    = "SELECT krs.id, mahasiswa.nama_mahasiswa, "
                    + "matkul.nama_matkul, "
                    + "krs.semester, krs.tahun_ajaran "
                    + "FROM krs "
                    + "JOIN mahasiswa "
                    + "ON krs.nim = mahasiswa.nim "
                    + "JOIN matkul "
                    + "ON krs.kode_matkul = matkul.kode_matkul";

            Statement st = conn.createStatement();

            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nama_mahasiswa"),
                    rs.getString("nama_matkul"),
                    rs.getString("semester"),
                    rs.getString("tahun_ajaran")
                });
            }
            tblKrs.setModel(model);
        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());
        }
    }

