    private void tampilMahasiswa() {
        try {
            cbMahasiswa.removeAllItems();
            cbMahasiswa.addItem("-- Pilih Mahasiswa --");
            Connection conn = Koneksi.getKoneksi();
            Statement st = conn.createStatement();

            ResultSet rs
                    = st.executeQuery("SELECT * FROM mahasiswa");

            while (rs.next()) {

                cbMahasiswa.addItem(
                        rs.getString("nim")
                        + " - "
                        + rs.getString("nama_mahasiswa")
                );
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());
        }
    }

