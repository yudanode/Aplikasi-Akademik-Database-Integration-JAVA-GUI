    private void tampilData() {

        DefaultTableModel model
                = new DefaultTableModel();

        model.addColumn("ID");
        model.addColumn("NIM");
        model.addColumn("Mata Kuliah");
        model.addColumn("Nilai");

        try {

            Connection conn
                    = Koneksi.getKoneksi();

            Statement st
                    = conn.createStatement();

            String sql
                    = "SELECT nilai.id, mahasiswa.nim, "
                    + "matkul.nama_matkul, nilai.nilai "
                    + "FROM nilai "
                    + "JOIN mahasiswa "
                    + "ON nilai.nim = mahasiswa.nim "
                    + "JOIN matkul "
                    + "ON nilai.kode_matkul = matkul.kode_matkul";

            ResultSet rs
                    = st.executeQuery(sql);

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nim"),
                    rs.getString("nama_matkul"),
                    rs.getString("nilai"),});

            }

            tblNilai.setModel(model);

        } catch (Exception e) {

            JOptionPane.showMessageDialog(
                    null,
                    e);

        }
    }

