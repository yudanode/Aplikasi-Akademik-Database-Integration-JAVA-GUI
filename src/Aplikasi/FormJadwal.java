    private void tampilData() {

        try {
            DefaultTableModel model
                    = new DefaultTableModel();
            model.addColumn("ID");
            model.addColumn("Kode Mata Kuliah");
            model.addColumn("NIDN");
            model.addColumn("Hari");
            model.addColumn("Jam");
            model.addColumn("Ruang");
            model.setRowCount(0);

            Connection conn = Koneksi.getKoneksi();

            String sql
                    = "SELECT jadwal.id, "
                    + "matkul.nama_matkul, "
                    + "dosen.nama_dosen, "
                    + "jadwal.hari, jadwal.jam, jadwal.ruang "
                    + "FROM jadwal "
                    + "JOIN matkul "
                    + "ON jadwal.kode_matkul = matkul.kode_matkul "
                    + "JOIN dosen "
                    + "ON jadwal.nidn = dosen.nidn";

            Statement st = conn.createStatement();

            ResultSet rs = st.executeQuery(sql);

            while (rs.next()) {

                model.addRow(new Object[]{
                    rs.getString("id"),
                    rs.getString("nama_matkul"),
                    rs.getString("nama_dosen"),
                    rs.getString("hari"),
                    rs.getString("jam"),
                    rs.getString("ruang")
                });
            }
            tblJadwal.setModel(model);
        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());
        }
    }

