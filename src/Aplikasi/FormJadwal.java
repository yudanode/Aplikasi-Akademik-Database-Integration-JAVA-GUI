    private void tampilMatkul() {

        try {
            cbMatkul.removeAllItems();

            cbMatkul.addItem("-- Pilih Mata Kuliah --");

            Connection conn = Koneksi.getKoneksi();

            Statement st = conn.createStatement();

            ResultSet rs
                    = st.executeQuery("SELECT * FROM matkul");

            while (rs.next()) {

                cbMatkul.addItem(
                        rs.getString("kode_matkul")
                        + " - "
                        + rs.getString("nama_matkul")
                );
            }

        } catch (Exception e) {

            JOptionPane.showMessageDialog(this,
                    e.getMessage());
        }
    }

